import 'package:flutter_test/flutter_test.dart';
import 'package:status_studio/src/features/source/domain/script_language.dart';
import 'package:status_studio/src/features/transcript/domain/caption_track_choice.dart';
import 'package:status_studio/src/features/transcript/domain/transcript_errors.dart';

CaptionTrackChoice track(String code, {required int index, bool auto = false}) =>
    CaptionTrackChoice(languageCode: code, isAutoGenerated: auto, index: index);

void main() {
  test('prefers_manual_track', () {
    final tracks = [track('ur', index: 0, auto: true), track('ur', index: 1)];

    expect(pickCaptionTrack(tracks, ScriptLanguage.urdu).index, 1);
  });

  test('auto_language_accepts_any_track', () {
    final tracks = [track('ar', index: 0, auto: true)];

    expect(pickCaptionTrack(tracks, ScriptLanguage.auto).index, 0);
  });

  test('ignores_tracks_in_other_language_when_language_chosen', () {
    final tracks = [track('en', index: 0, auto: true)];

    expect(
      () => pickCaptionTrack(tracks, ScriptLanguage.urdu),
      throwsA(isA<NoCaptionTrackException>()),
    );
  });

  test('matches_regional_variant_of_chosen_language', () {
    final tracks = [track('en-GB', index: 0)];

    expect(pickCaptionTrack(tracks, ScriptLanguage.english).index, 0);
  });

  test('no_tracks_throws', () {
    expect(
      () => pickCaptionTrack(const [], ScriptLanguage.auto),
      throwsA(isA<NoCaptionTrackException>()),
    );
  });

  test('captions_become_numbered_lines_without_empty_ones', () {
    final lines = linesFromCaptions(const [
      CaptionCue(text: ' first ', start: Duration.zero, end: Duration(seconds: 2)),
      CaptionCue(text: '  ', start: Duration(seconds: 2), end: Duration(seconds: 3)),
      CaptionCue(
        text: 'second',
        start: Duration(seconds: 3),
        end: Duration(seconds: 5),
      ),
    ]);

    expect(lines.map((line) => (line.index, line.text)), [
      (0, 'first'),
      (1, 'second'),
    ]);
  });

  test('base_language_code_drops_region', () {
    expect(baseLanguageCode('en-GB'), 'en');
  });
}

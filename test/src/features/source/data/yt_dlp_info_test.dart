import 'package:flutter_test/flutter_test.dart';
import 'package:status_studio/src/features/source/data/yt_dlp_info.dart';
import 'package:status_studio/src/features/source/domain/source_errors.dart';

Map<String, Object?> audioFormat(
  String id, {
  required String ext,
  required double abr,
  int languagePreference = -1,
}) => {
  'format_id': id,
  'ext': ext,
  'acodec': ext == 'm4a' ? 'mp4a.40.5' : 'opus',
  'vcodec': 'none',
  'abr': abr,
  'tbr': abr,
  'protocol': 'https',
  'filesize': 3342572,
  'language_preference': languagePreference,
  'url': 'https://media.example/audio/$id',
};

Map<String, Object?> videoFormat(
  String id, {
  required int height,
  String protocol = 'https',
  int? filesize = 21229386,
}) => {
  'format_id': id,
  'ext': 'mp4',
  'acodec': 'none',
  'vcodec': 'avc1.4d401e',
  'width': height * 16 ~/ 9,
  'height': height,
  'tbr': 310.5,
  'protocol': protocol,
  'filesize': filesize,
  'url': 'https://media.example/video/$id',
};

Map<String, Object?> captionFormats(String lang) => {
  'formats': [
    {'ext': 'srv3', 'url': 'https://captions.example/$lang.srv3'},
    {'ext': 'json3', 'url': 'https://captions.example/$lang.json3'},
  ],
};

Map<String, Object?> videoJson({
  Object? duration = 548,
  bool isLive = false,
  List<Map<String, Object?>>? formats,
  Map<String, Object?> subtitles = const {},
  Map<String, Object?> automaticCaptions = const {},
}) => {
  'id': 's6kE_uP3xH4',
  'title': 'Main Madine Chala',
  'channel': 'Heera Gold',
  'uploader': 'Heera Gold uploads',
  'duration': duration,
  'is_live': isLive,
  'formats':
      formats ??
      [
        audioFormat('139', ext: 'm4a', abr: 48.8),
        audioFormat('251', ext: 'webm', abr: 140),
        videoFormat('134', height: 360),
      ],
  'subtitles': {
    for (final MapEntry(:key, :value) in subtitles.entries)
      key: (value as Map<String, Object?>)['formats'],
  },
  'automatic_captions': {
    for (final MapEntry(:key, :value) in automaticCaptions.entries)
      key: (value as Map<String, Object?>)['formats'],
  },
};

void main() {
  test('reads_title_channel_and_length', () {
    final video = YtDlpInfo.fromJson(videoJson()).video;

    expect(
      [video.videoId, video.title, video.channel, video.duration],
      [
        's6kE_uP3xH4',
        'Main Madine Chala',
        'Heera Gold',
        const Duration(minutes: 9, seconds: 8),
      ],
    );
  });

  test('live_stream_is_unavailable', () {
    expect(
      () => YtDlpInfo.fromJson(videoJson(isLive: true)),
      throwsA(isA<VideoUnavailableException>()),
    );
  });

  test('video_without_a_length_is_unavailable', () {
    expect(
      () => YtDlpInfo.fromJson(videoJson(duration: null)),
      throwsA(isA<VideoUnavailableException>()),
    );
  });

  test('skips_hls_formats', () {
    final info = YtDlpInfo.fromJson(
      videoJson(
        formats: [
          audioFormat('139', ext: 'm4a', abr: 48.8),
          videoFormat('134', height: 360),
          videoFormat(
            '230',
            height: 360,
            protocol: 'm3u8_native',
            filesize: null,
          ),
        ],
      ),
    );

    expect(info.videoFormats.map((format) => '${format.url}'), [
      'https://media.example/video/134',
    ]);
  });

  test('audio_m4a_counts_as_mp4', () {
    final info = YtDlpInfo.fromJson(videoJson());

    expect(info.audioFormats.map((format) => format.choice.container), [
      'mp4',
      'webm',
    ]);
  });

  test('bitrate_is_in_bits_per_second', () {
    final info = YtDlpInfo.fromJson(videoJson());

    expect(info.audioFormats.first.choice.bitrate, 48800);
  });

  test('original_audio_track_is_default', () {
    final info = YtDlpInfo.fromJson(
      videoJson(
        formats: [
          audioFormat('139-dubbed', ext: 'm4a', abr: 48.8),
          audioFormat(
            '139-original',
            ext: 'm4a',
            abr: 48.8,
            languagePreference: 10,
          ),
        ],
      ),
    );

    expect(info.audioFormats.map((format) => format.choice.isDefaultTrack), [
      false,
      true,
    ]);
  });

  test('auto_captions_use_only_the_orig_track', () {
    final info = YtDlpInfo.fromJson(
      videoJson(
        automaticCaptions: {
          'ro-orig': captionFormats('ro-orig'),
          'ro': captionFormats('ro'),
          'ur': captionFormats('ur'),
        },
      ),
    );

    expect(
      info.captionTracks.map(
        (track) => [
          track.choice.languageCode,
          track.choice.isAutoGenerated,
          '${track.json3Url}',
        ],
      ),
      [
        ['ro', true, 'https://captions.example/ro-orig.json3'],
      ],
    );
  });

  test('live_chat_is_not_a_caption_track', () {
    final info = YtDlpInfo.fromJson(
      videoJson(
        subtitles: {
          'live_chat': captionFormats('live_chat'),
          'en': captionFormats('en'),
        },
      ),
    );

    expect(info.captionTracks.map((track) => track.choice.languageCode), [
      'en',
    ]);
  });
}

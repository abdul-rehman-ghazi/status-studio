const Map<String, String> _punctuation = {
  '۔': '.',
  '،': ',',
  '؟': '?',
  '؛': ';',
};

/// Runs of Arabic-script letters, digits and marks: the words to convert.
final _word = RegExp(
  r'[\u0621-\u065F\u0660-\u0669\u0670-\u06D3\u06D5\u06F0-\u06F9]+',
);

/// Rule-based Roman Urdu (spec §6.6): known words from [romanUrduWords],
/// the rest letter by letter. Imperfect by design; the caption stays
/// editable. Spacing and line breaks are kept.
String romanizeUrdu(String text) {
  final words = text.replaceAllMapped(
    _word,
    (match) => _romanizeWord(match.group(0)!),
  );
  return words
      .split('')
      .map((character) => _punctuation[character] ?? character)
      .join();
}

String _romanizeWord(String word) {
  final known = romanUrduWords[word];
  if (known != null) {
    return known;
  }
  return word.split('').map((letter) => _letters[letter] ?? '').join();
}

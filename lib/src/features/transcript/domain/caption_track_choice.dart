/// One caption track YouTube offers, reduced to what choosing needs.
@immutable
class CaptionTrackChoice {
  const CaptionTrackChoice({
    required this.languageCode,
    required this.isAutoGenerated,
    required this.index,
  });

  final String languageCode;
  final bool isAutoGenerated;

  /// Position in the manifest list this choice came from.
  final int index;

  @override
  bool operator ==(Object other) =>
      other is CaptionTrackChoice &&
      other.languageCode == languageCode &&
      other.isAutoGenerated == isAutoGenerated &&
      other.index == index;

  @override
  int get hashCode => Object.hash(languageCode, isAutoGenerated, index);
}

/// One timed caption from a track.
@immutable
class CaptionCue {
  const CaptionCue({
    required this.text,
    required this.start,
    required this.end,
  });

  final String text;
  final Duration start;
  final Duration end;

  @override
  bool operator ==(Object other) =>
      other is CaptionCue &&
      other.text == text &&
      other.start == start &&
      other.end == end;

  @override
  int get hashCode => Object.hash(text, start, end);
}

/// A track in [language], manual tracks over auto-generated ones (FR-3).
/// With automatic language only manual tracks count: YouTube guesses an
/// auto-generated track's language from the audio, and a wrong guess (an
/// Urdu naat captioned as Romanian) makes the whole script junk, so
/// Whisper writes it instead. Throws [NoCaptionTrackException].
CaptionTrackChoice pickCaptionTrack(
  List<CaptionTrackChoice> tracks,
  ScriptLanguage language,
) {
  final matching = language == ScriptLanguage.auto
      ? tracks.where((track) => !track.isAutoGenerated)
      : tracks.where(
          (track) =>
              baseLanguageCode(track.languageCode) == language.whisperCode,
        );
  if (matching.isEmpty) {
    throw const NoCaptionTrackException();
  }
  return matching.firstWhere(
    (track) => !track.isAutoGenerated,
    orElse: () => matching.first,
  );
}

/// `en-GB` → `en`: YouTube tags regional variants, Whisper doesn't.
String baseLanguageCode(String code) => code.split('-').first.toLowerCase();

/// Each non-empty caption becomes one line, numbered in order.
List<TranscriptLine> linesFromCaptions(List<CaptionCue> cues) {
  final spoken = cues
      .map((cue) => (cue: cue, text: cue.text.trim()))
      .where((entry) => entry.text.isNotEmpty)
      .toList();
  return [
    for (final (index, entry) in spoken.indexed)
      TranscriptLine(
        index: index,
        text: entry.text,
        start: entry.cue.start,
        end: entry.cue.end,
      ),
  ];
}
